import assert from 'node:assert/strict';
import {connectorStatus,startConnector} from './xhs_connector_health.mjs';
const ready={daemonVersion:'2.0.2',profiles:[{contextId:'profile_alpha'}]};
const failure=code=>async()=>{throw Object.assign(new Error('fetch failed'),{cause:{code}});};
for(const code of ['EPERM','EACCES']) await assert.rejects(()=>connectorStatus(failure(code)),/CONNECTOR_PERMISSION_DENIED/);
assert.equal(await connectorStatus(failure('ECONNREFUSED')),null);
await assert.rejects(()=>connectorStatus(failure('ETIMEDOUT')),/CONNECTOR_STATUS_TIMEOUT/);
await assert.rejects(()=>connectorStatus(failure('UNKNOWN')),/CONNECTOR_STATUS_UNAVAILABLE/);
await assert.rejects(()=>connectorStatus(async()=>({ok:false})),/CONNECTOR_STATUS_HTTP_ERROR/);
await assert.rejects(()=>connectorStatus(async()=>({ok:true,json:async()=>({})})),/CONNECTOR_STATUS_INVALID/);
assert.deepEqual(await connectorStatus(async()=>({ok:true,json:async()=>ready})),ready);
let spawns=0;const spawn=()=>{spawns++;return {};};const opts={attempts:2,sleep:async()=>{}};
assert.equal(await startConnector(async()=>ready,spawn,'2.0.2',opts),ready);assert.equal(spawns,0);
await assert.rejects(()=>startConnector(()=>connectorStatus(failure('EPERM')),spawn,'2.0.2',opts),/PERMISSION/);assert.equal(spawns,0);
await assert.rejects(()=>startConnector(async()=>({...ready,daemonVersion:'other'}),spawn,'2.0.2',opts),/DAEMON_CHANGED/);assert.equal(spawns,0);
let probes=0;assert.equal(await startConnector(async()=>++probes===1?null:ready,spawn,'2.0.2',opts),ready);assert.equal(spawns,1);
await assert.rejects(()=>startConnector(async()=>null,spawn,'2.0.2',opts),/START_FAILED/);assert.equal(spawns,2);
probes=0;await assert.rejects(()=>startConnector(async()=>++probes===1?null:{...ready,daemonVersion:'other'},spawn,'2.0.2',opts),/DAEMON_CHANGED/);
console.log('14 connector health scenarios passed');
